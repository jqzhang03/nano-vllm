def _int_list(value: str, name: str) -> list[int]:
    try:
        values = [int(item.strip()) for item in value.split(",") if item.strip()]
    except ValueError as exc:
        raise argparse.ArgumentTypeError(f"{name} must be comma-separated integers") from exc
    if not values or any(item <= 0 for item in values):
        raise argparse.ArgumentTypeError(f"{name} values must all be positive")
    return sorted(set(values))


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--model", default=os.path.expanduser("~/huggingface/Qwen3-0.6B"))
    parser.add_argument("--context-lengths", type=lambda x: _int_list(x, "context-lengths"),
                        default=[512, 1024, 2048, 4096],
                        help="prompt token lengths, comma separated")
    parser.add_argument("--concurrency", type=lambda x: _int_list(x, "concurrency"),
                        default=[1, 2, 4, 8, 16],
                        help="simultaneous request burst sizes, comma separated")
    parser.add_argument("--repeats", type=int, default=3,
                        help="independent bursts per matrix point")
    parser.add_argument("--max-output-tokens", type=int, default=32)
    parser.add_argument("--kv-cache-dtype", choices=("auto", "fp8_e4m3"), default="auto")
    parser.add_argument("--kv-calibration-path", default="",
                        help="token-ID JSON generated by kv_fp8_calibrate.py (FP8 only)")
    parser.add_argument("--kv-fp8-scale-margin", type=float, default=1.1)
    parser.add_argument("--quantization",
                        choices=("none", "w8a8", "int4", "awq", "fp8", "sparse24"),
                        default="none", help="weight quantization mode")
    parser.add_argument("--rolling-cache", action="store_true",
                        help="enable SWA ring cache for supported Mistral/Gemma-2 models")
    parser.add_argument("--no-swap-kv", action="store_true",
                        help="disable CPU KV swap (recompute preemption remains available)")
    parser.add_argument("--kv-swap-space-gb", type=float, default=2.0,
                        help="maximum host-memory budget for swapped KV blocks")
    parser.add_argument("--no-mixed-cudagraph", action="store_true",
                        help="disable lazy mixed-batch CUDA Graph capture")
    parser.add_argument("--gpu-memory-utilization", type=float, default=0.9)
    parser.add_argument("--max-num-batched-tokens", type=int, default=16384)
    parser.add_argument("--enforce-eager", action="store_true")
    parser.add_argument("--dynamic-admission", action="store_true",
                        help="also enable predictive accept/defer/reject admission")
    parser.add_argument("--ttft-slo-ms", type=float, default=500.0,
                        help="TTFT target supplied to the SLO-aware scheduler")
    parser.add_argument("--tpot-slo-ms", type=float, default=10.0,
                        help="TPOT target reported as an SLO metric")
    parser.add_argument("--max-queued-requests", type=int, default=512)
    parser.add_argument("--max-deferred-requests", type=int, default=64)
    parser.add_argument("--max-admission-wait-ms", type=float, default=2000.0)
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--output", default=None,
                        help="JSON output path; CSV is written with the same stem")
    args = parser.parse_args()
    if args.repeats < 1 or args.max_output_tokens < 1:
        parser.error("--repeats and --max-output-tokens must be positive")
    if args.max_num_batched_tokens < 1:
        parser.error("--max-num-batched-tokens must be positive")
    if args.ttft_slo_ms <= 0 or not math.isfinite(args.ttft_slo_ms):
        parser.error("--ttft-slo-ms must be a finite positive number")
    if args.tpot_slo_ms <= 0 or not math.isfinite(args.tpot_slo_ms):
        parser.error("--tpot-slo-ms must be a finite positive number")
    if args.kv_fp8_scale_margin <= 0 or not math.isfinite(args.kv_fp8_scale_margin):
        parser.error("--kv-fp8-scale-margin must be a finite positive number")
    if args.kv_cache_dtype == "auto" and args.kv_calibration_path:
        parser.error("--kv-calibration-path requires --kv-cache-dtype fp8_e4m3")
    if args.kv_swap_space_gb < 0 or not math.isfinite(args.kv_swap_space_gb):
        parser.error("--kv-swap-space-gb must be finite and non-negative")
    return args


def _percentiles(values: list[float | None]) -> dict[str, float | int | None]:
    vals = sorted(float(value) for value in values if value is not None)
    if not vals:
        return {"avg": None, "p50": None, "p90": None, "p99": None,
                "min": None, "max": None, "count": 0}

    def pick(q: float) -> float:
        return vals[min(int(math.ceil(q * len(vals))) - 1, len(vals) - 1)]

    return {"avg": statistics.fmean(vals), "p50": pick(0.50), "p90": pick(0.90),
            "p99": pick(0.99), "min": vals[0], "max": vals[-1], "count": len(vals)}


def _dtype_itemsize(dtype: torch.dtype) -> int:
    return torch.empty((), dtype=dtype).element_size()


def kv_capacity_report(engine: LLM, context_lengths: list[int], output_tokens: int) -> dict:
    runner = engine.model_runner
    config = engine.config
    hf = config.hf_config
    block_size = config.kvcache_block_size
    kv_dtype = runner.kv_cache.dtype
    cache_tensors: list[tuple[str, torch.Tensor, int]] = []
    if hasattr(runner, "kv_cache_full"):
        cache_tensors.append(("rolling", runner.kv_cache,
                              int(config.num_ring_kvcache_blocks)))
        cache_tensors.append(("full", runner.kv_cache_full,
                              int(config.num_full_kvcache_blocks)))
    else:
        cache_tensors.append(("standard", runner.kv_cache,
                              int(config.num_kvcache_blocks)))

    pools = []
    for name, tensor, blocks in cache_tensors:
        pools.append({
            "name": name,
            "blocks": blocks,
            "block_size_tokens": block_size,
            "capacity_token_slots": blocks * block_size,
            "allocated_bytes": tensor.numel() * tensor.element_size(),
            "bytes_per_capacity_token": (
                tensor.numel() * tensor.element_size() / max(1, blocks * block_size)),
        })

    if hasattr(hf, "kv_lora_rank"):
        auto_bytes_per_token = (hf.num_hidden_layers
                                * (hf.kv_lora_rank + hf.qk_rope_head_dim)
                                * _dtype_itemsize(hf.dtype))
        cache_layout = "MLA fused latent cache"
    else:
        heads = hf.num_key_value_heads // config.tensor_parallel_size
        head_dim = getattr(hf, "head_dim", hf.hidden_size // hf.num_attention_heads)
        auto_bytes_per_token = (2 * hf.num_hidden_layers * heads * head_dim
                                * _dtype_itemsize(hf.dtype))
        cache_layout = "MHA K/V cache"

    manager = engine.scheduler.block_manager
    pool_managers = {"standard": manager}
    if manager.full_block_manager is not None:
        pool_managers = {
            "rolling": manager,
            "full": manager.full_block_manager,
        }

    simultaneous = {}
    for context_len in context_lengths:
        reserved_tokens = context_len + output_tokens
        prompt_blocks = math.ceil(context_len / block_size)
        full_history_blocks = math.ceil(reserved_tokens / block_size)
        per_pool = {}
        for name, pool_manager in pool_managers.items():
            needed = full_history_blocks
            if pool_manager.rolling:
                # Allocation initially reserves the whole prompt. Once decode
                # advances, old blocks are evicted and use is bounded by ring_cap.
                needed = max(prompt_blocks, min(full_history_blocks,
                                                pool_manager.ring_cap))
            needed = max(1, needed)
            total_blocks = len(pool_manager.blocks)
            per_pool[name] = {
                "blocks_per_request": needed,
                "max_requests": total_blocks // needed,
                "rolling_ring_cap_blocks": (pool_manager.ring_cap
                                             if pool_manager.rolling else None),
            }
        simultaneous[str(context_len)] = {
            "tokens_per_request_reserved": reserved_tokens,
            "blocks_per_request_per_pool": {
                name: values["blocks_per_request"]
                for name, values in per_pool.items()},
            "max_requests_per_pool": {
                name: values["max_requests"] for name, values in per_pool.items()},
            "max_full_context_requests": min(
                values["max_requests"] for values in per_pool.values()),
        }

    free, total = torch.cuda.mem_get_info(runner.device)
    return {
        "layout": cache_layout,
        "kv_cache_dtype": config.kv_cache_dtype,
        "tensor_dtype": str(kv_dtype),
        "block_size_tokens": block_size,
        "pools": pools,
        "allocated_cache_bytes": sum(pool["allocated_bytes"] for pool in pools),
        "allocated_capacity_token_slots": sum(
            pool["capacity_token_slots"] for pool in pools),
        "actual_weighted_bytes_per_capacity_token": (
            sum(pool["allocated_bytes"] for pool in pools)
            / max(1, sum(pool["capacity_token_slots"] for pool in pools))),
        "theoretical_auto_bytes_per_token": auto_bytes_per_token,
        "theoretical_fp8_bytes_per_token": auto_bytes_per_token / _dtype_itemsize(hf.dtype),
        "theoretical_capacity_multiplier_fp8": _dtype_itemsize(hf.dtype),
        "max_full_context_requests_by_prompt_length": simultaneous,
        "gpu_total_bytes": total,
        "gpu_free_bytes_after_engine_init": free,
        "gpu_memory_utilization_target": config.gpu_memory_utilization,
        "pytorch_allocated_bytes_after_engine_init": torch.cuda.memory_allocated(runner.device),
        "pytorch_reserved_bytes_after_engine_init": torch.cuda.memory_reserved(runner.device),
    }


def make_prompts(concurrency: int, context_len: int, repeat: int,
                 vocab_size: int, seed: int) -> list[list[int]]:
    rng = random.Random(seed + context_len * 1009 + concurrency * 9176 + repeat * 37)
    # Match the existing synthetic workload convention and avoid special IDs at
    # the top of the vocabulary, which often contain reserved control tokens.
    upper = max(2, min(vocab_size, 10000))
    return [[rng.randrange(upper) for _ in range(context_len)]
            for _ in range(concurrency)]


def cudagraph_capacity(max_concurrency: int) -> int:
    """Round to a graph capture family that exists in ModelRunner."""
    return max_concurrency if max_concurrency <= 8 else math.ceil(max_concurrency / 16) * 16


async def run_scenario(engine: LLM, executor: ThreadPoolExecutor,
                       args: argparse.Namespace, context_len: int,
                       concurrency: int) -> dict:
    engine.reset_benchmark_metrics()
    max_queue = max(args.max_queued_requests, concurrency)
    manager = GenerationManager(
        engine, executor, max_queue,
        dynamic_admission=args.dynamic_admission,
        max_deferred_requests=args.max_deferred_requests,
        max_admission_wait_ms=args.max_admission_wait_ms,
        admission_target_ttft_ms=args.ttft_slo_ms,
        admission_work_budget_ms=1e9,
        admission_soft_pressure=1.0,
    )
    manager.start()
    all_rows = []
    burst_walls = []
    start_allocated = torch.cuda.memory_allocated(engine.model_runner.device)
    torch.cuda.reset_peak_memory_stats(engine.model_runner.device)
    try:
        for repeat in range(args.repeats):
            prompts = make_prompts(concurrency, context_len, repeat,
                                   engine.config.hf_config.vocab_size, args.seed)
            sampling = SamplingParams(temperature=0.6, ignore_eos=True,
                                      max_tokens=args.max_output_tokens)
            burst_start = time.perf_counter()
            arrival = burst_start

            async def submit_one(index: int) -> dict:
                try:
                    handle = await manager.submit(
                        prompts[index], sampling, submitted_at=arrival,
                        ttft_slo_ms=args.ttft_slo_ms)
                except Exception as exc:
                    return {"index": index, "repeat": repeat, "status": "rejected",
                            "error": str(exc)}
                result = await handle.result
                return {
                    "index": index,
                    "repeat": repeat,
                    "status": "accepted" if "error" not in result else "failed",
                    "seq_id": handle.seq_id,
                    "prompt_tokens": context_len,
                    "completion_tokens": len(result.get("token_ids", [])),
                    "admission_decision": handle.admission_decision,
                    "admission_wait_ms": handle.admission_wait_ms,
                    "predicted_ttft_ms": handle.predicted_ttft_ms,
                    "queue_pressure": handle.queue_pressure,
                    "ttft_ms": ((handle.first_token_at - arrival) * 1000.0
                                if handle.first_token_at is not None else None),
                    "e2e_ms": ((handle.completed_at - arrival) * 1000.0
                               if handle.completed_at is not None else None),
                    "error": result.get("error"),
                }

            rows = await asyncio.gather(*(submit_one(i) for i in range(concurrency)))
            burst_walls.append(time.perf_counter() - burst_start)
            all_rows.extend(rows)
    finally:
        await manager.close()

    torch.cuda.synchronize(engine.model_runner.device)
    # Exclude synthetic prompt construction between repeats; throughput uses
    # the sum of the measured burst intervals from arrival to completion.
    total_wall = sum(burst_walls)
    seq_metrics = {row["seq_id"]: row for row in engine._req_metrics}
    for row in all_rows:
        details = seq_metrics.get(row.get("seq_id"), {})
        submitted = details.get("t_submitted")
        prefill_started = details.get("t_prefill_started")
        row["queue_wait_ms"] = (
            (prefill_started - submitted) * 1000.0
            if submitted is not None and prefill_started is not None else None)
        row["prefix_cached_tokens"] = details.get("prefix_cached_tokens", 0)
        ttft, e2e = row.get("ttft_ms"), row.get("e2e_ms")
        count = row.get("completion_tokens", 0)
        row["average_tpot_ms"] = (
            max(0.0, e2e - ttft) / (count - 1)
            if ttft is not None and e2e is not None and count > 1 else None)

    accepted = [row for row in all_rows if row["status"] == "accepted"]
    output_tokens = sum(row["completion_tokens"] for row in accepted)
    input_tokens = sum(row["prompt_tokens"] for row in accepted)
    metrics = engine.collect_metrics()
    admission = manager.admission_snapshot()
    prefill_tokens_processed = admission["step_stats"]["prefill_tokens"]
    peak_allocated = torch.cuda.max_memory_allocated(engine.model_runner.device)
    peak_reserved = torch.cuda.max_memory_reserved(engine.model_runner.device)
    kv_budget = kv_capacity_report(engine, [context_len], args.max_output_tokens)
    ttfts = [row["ttft_ms"] for row in accepted]
    e2es = [row["e2e_ms"] for row in accepted]
    tpots = [row["average_tpot_ms"] for row in accepted]
    queue_waits = [row["queue_wait_ms"] for row in accepted]
    admission_waits = [row.get("admission_wait_ms") for row in all_rows
                       if row.get("admission_wait_ms") is not None]
    predicted_ttfts = [row.get("predicted_ttft_ms") for row in all_rows
                       if row.get("predicted_ttft_ms") is not None]
    queue_pressures = [row.get("queue_pressure") for row in all_rows
                       if row.get("queue_pressure") is not None]
    return {
        "context_length": context_len,
        "concurrency": concurrency,
        "repeats": args.repeats,
        "requests": len(all_rows),
        "accepted": len(accepted),
        "rejected": sum(row["status"] == "rejected" for row in all_rows),
        "failed": sum(row["status"] == "failed" for row in all_rows),
        "admission_accepted": admission["accepted"],
        "admission_deferred_total": admission["deferred_total"],
        "admission_rejected": admission["rejected"],
        "admission_deferred_timeouts": admission["deferred_timeouts"],
        "acceptance_percent": 100.0 * len(accepted) / max(1, len(all_rows)),
        "wall_seconds": total_wall,
        "mean_burst_wall_seconds": statistics.fmean(burst_walls),
        "input_tokens": input_tokens,
        "prefill_tokens_processed": prefill_tokens_processed,
        "output_tokens": output_tokens,
        "input_tokens_per_second": input_tokens / max(total_wall, 1e-12),
        "prefill_tokens_per_second": prefill_tokens_processed / max(total_wall, 1e-12),
        "output_tokens_per_second": output_tokens / max(total_wall, 1e-12),
        "total_tokens_per_second": (input_tokens + output_tokens) / max(total_wall, 1e-12),
        "requests_per_second": len(accepted) / max(total_wall, 1e-12),
        "ttft_ms": _percentiles(ttfts),
        "average_tpot_ms": _percentiles(tpots),
        "e2e_ms": _percentiles(e2es),
        "queue_wait_ms": _percentiles(queue_waits),
        "ttft_slo_target_ms": args.ttft_slo_ms,
        "tpot_slo_target_ms": args.tpot_slo_ms,
        "ttft_slo_met_percent": (
            100.0 * sum(value <= args.ttft_slo_ms for value in ttfts) / max(1, len(ttfts))),
        "tpot_slo_met_percent": (
            100.0 * sum(value <= args.tpot_slo_ms for value in tpots if value is not None)
            / max(1, sum(value is not None for value in tpots))),
        "admission_wait_ms": _percentiles(admission_waits),
        "predicted_ttft_ms": _percentiles(predicted_ttfts),
        "admission_queue_pressure": _percentiles(queue_pressures),
        "prefix_cache_hit_tokens": metrics["prefix_cache_hit_tokens"],
        "prefix_cache_hit_requests": metrics["prefix_cache_hit_requests"],
        "preemptions": metrics["num_preemptions"],
        "swaps": metrics["num_swaps"],
        "recompute_preemptions": metrics["num_recompute_preemptions"],
        "recompute_tokens": metrics["recompute_tokens"],
        "decode_cudagraph": metrics["decode_cudagraph"],
        "mixed_cudagraph": metrics["mixed_cudagraph"],
        "engine_steps": admission["step_stats"],
        "admission": admission,
        "kv_pool_usage": admission["kv_pools"],
        "kv_capacity_budget": kv_budget,
        "gpu_memory": {
            "allocated_before_benchmark_bytes": start_allocated,
            "peak_allocated_bytes": peak_allocated,
            "peak_allocated_delta_bytes": max(0, peak_allocated - start_allocated),
            "peak_reserved_bytes": peak_reserved,
        },
        "per_request": all_rows,
    }


def _csv_rows(results: list[dict]) -> list[dict]:
    rows = []
    for result in results:
        row = {key: result[key] for key in (
            "context_length", "concurrency", "repeats", "requests", "accepted",
            "rejected", "failed", "acceptance_percent", "wall_seconds",
            "ttft_slo_target_ms", "tpot_slo_target_ms", "ttft_slo_met_percent",
            "tpot_slo_met_percent",
            "admission_accepted", "admission_deferred_total", "admission_rejected",
            "admission_deferred_timeouts",
            "input_tokens_per_second", "output_tokens_per_second",
            "prefill_tokens_processed", "prefill_tokens_per_second",
            "total_tokens_per_second", "requests_per_second", "preemptions", "swaps",
            "recompute_preemptions", "prefix_cache_hit_tokens")}
        for graph_name in ("decode_cudagraph", "mixed_cudagraph"):
            graph = result[graph_name]
            row[f"{graph_name}_enabled"] = graph["enabled"]
            row[f"{graph_name}_replays"] = graph["replays"]
            row[f"{graph_name}_eager_fallbacks"] = graph["eager_fallbacks"]
            row[f"{graph_name}_fallback_reason"] = graph["fallback_reason"]
        row["decode_cudagraph_captured_batch_sizes"] = ",".join(
            str(size) for size in result["decode_cudagraph"]["captured_batch_sizes"])
        row["mixed_cudagraph_captures"] = result["mixed_cudagraph"]["captures"]
        for metric in ("ttft_ms", "average_tpot_ms", "e2e_ms", "queue_wait_ms",
                       "admission_wait_ms", "predicted_ttft_ms",
                       "admission_queue_pressure"):
            for stat in ("avg", "p50", "p90", "p99", "min", "max"):
                row[f"{metric}_{stat}"] = result[metric][stat]
        row["kv_cache_bytes"] = result["kv_capacity_budget"]["allocated_cache_bytes"]
        row["kv_cache_dtype"] = result["kv_capacity_budget"]["kv_cache_dtype"]
        row["kv_capacity_token_slots"] = result["kv_capacity_budget"][
            "allocated_capacity_token_slots"]
        pools = result["kv_pool_usage"]
        row["kv_total_blocks"] = sum(pool["total_blocks"] for pool in pools)
        row["kv_peak_used_blocks"] = max(
            (pool["peak_used_blocks"] for pool in pools), default=0)
        row["kv_peak_pool_utilization"] = max(
            (pool["peak_used_blocks"] / pool["total_blocks"]
             for pool in pools if pool["total_blocks"]), default=0.0)
        row["max_full_context_requests"] = result["kv_capacity_budget"][
            "max_full_context_requests_by_prompt_length"][str(result["context_length"])]\
            ["max_full_context_requests"]
        capacity = result["kv_capacity_budget"][
            "max_full_context_requests_by_prompt_length"][str(result["context_length"])]
        for pool_name, max_requests in capacity["max_requests_per_pool"].items():
            row[f"{pool_name}_pool_max_requests"] = max_requests
            row[f"{pool_name}_pool_blocks_per_request"] = capacity[
                "blocks_per_request_per_pool"][pool_name]
        row["gpu_peak_allocated_bytes"] = result["gpu_memory"]["peak_allocated_bytes"]
        row["gpu_peak_reserved_bytes"] = result["gpu_memory"]["peak_reserved_bytes"]
        rows.append(row)
    return rows


def main() -> None:
    args = parse_args()
    args.model = os.path.expanduser(args.model)
    if not os.path.isdir(args.model):
        raise SystemExit(f"model directory does not exist: {args.model}")
    if not torch.cuda.is_available():
        raise SystemExit("CUDA is required to run the inference benchmark")
    if max(args.concurrency) > 512:
        raise SystemExit("maximum concurrency is 512 (the current CUDA graph batch limit)")
    hf = AutoConfig.from_pretrained(args.model)
    model_limit = int(getattr(hf, "max_position_embeddings", 4096))
    max_model_len = max(args.context_lengths) + args.max_output_tokens
    if max_model_len > model_limit:
        raise SystemExit(
            f"max prompt + output is {max_model_len} tokens, above the model limit "
            f"({model_limit}); lower the sweep or use a long-context model/config")
    if args.max_num_batched_tokens < max(args.context_lengths):
        print("note: context lengths exceed the per-step token budget and will be chunk-prefilled")

    # Keep the active sequence capacity close to the test's largest concurrency,
    # rounded to a captured family for values above eight.
    engine = LLM(
        args.model,
        execution_mode="mixed",
        tensor_parallel_size=1,
        max_model_len=max_model_len,
        max_num_seqs=cudagraph_capacity(max(args.concurrency)),
        max_num_batched_tokens=args.max_num_batched_tokens,
        gpu_memory_utilization=args.gpu_memory_utilization,
        enforce_eager=args.enforce_eager,
        kv_cache_dtype=args.kv_cache_dtype,
        kv_calibration_path=args.kv_calibration_path,
        kv_fp8_scale_margin=args.kv_fp8_scale_margin,
        quantization=args.quantization,
        rolling_cache=args.rolling_cache,
        kv_swap=not args.no_swap_kv,
        kv_swap_space_gb=args.kv_swap_space_gb,
        mixed_cudagraph=not args.no_mixed_cudagraph,
    )
    executor = ThreadPoolExecutor(max_workers=1, thread_name_prefix="context-bench")
    results = []
    try:
        matrix = [(context, concurrency) for context in args.context_lengths
                  for concurrency in args.concurrency]
        for index, (context, concurrency) in enumerate(matrix, 1):
            print(f"[{index}/{len(matrix)}] prompt={context} tokens, "
                  f"concurrency={concurrency}, repeats={args.repeats}", flush=True)
            result = asyncio.run(run_scenario(
                engine, executor, args, context, concurrency))
            results.append(result)
            print(f"  accepted {result['accepted']}/{result['requests']} | "
                  f"output {result['output_tokens_per_second']:.1f} tok/s | "
                  f"TTFT p50/p99 {result['ttft_ms']['p50'] or 0:.1f}/"
                  f"{result['ttft_ms']['p99'] or 0:.1f} ms | "
                  f"E2E p99 {result['e2e_ms']['p99'] or 0:.1f} ms", flush=True)
    finally:
        executor.shutdown(wait=True)
        engine.exit()
        torch.cuda.empty_cache()

    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    output = args.output or os.path.join(
        "results", f"context_concurrency_{timestamp}.json")
    output = os.path.expanduser(output)
    os.makedirs(os.path.dirname(output) or ".", exist_ok=True)
    payload = {
        "schema_version": 1,
        "meta": {"model": args.model, "date": timestamp, **env_info()},
        "config": {
            "context_lengths": args.context_lengths,
            "concurrency": args.concurrency,
            "repeats": args.repeats,
            "max_output_tokens": args.max_output_tokens,
            "kv_cache_dtype": args.kv_cache_dtype,
            "kv_fp8_scale_margin": args.kv_fp8_scale_margin,
            "quantization": args.quantization,
            "rolling_cache": args.rolling_cache,
            "kv_swap": not args.no_swap_kv,
            "kv_swap_space_gb": args.kv_swap_space_gb,
            "mixed_cudagraph": not args.no_mixed_cudagraph,
            "max_num_batched_tokens": args.max_num_batched_tokens,
            "dynamic_admission": args.dynamic_admission,
            "max_deferred_requests": args.max_deferred_requests,
            "max_admission_wait_ms": args.max_admission_wait_ms,
            "ttft_slo_ms": args.ttft_slo_ms,
            "tpot_slo_ms": args.tpot_slo_ms,
            "enforce_eager": args.enforce_eager,
            "seed": args.seed,
        },
        "results": results,
    }
    with open(output, "w", encoding="utf-8") as result_file:
        json.dump(payload, result_file, indent=2, default=str)
    csv_path = os.path.splitext(output)[0] + ".csv"
    rows = _csv_rows(results)
    with open(csv_path, "w", encoding="utf-8", newline="") as csv_file:
        import csv
        writer = csv.DictWriter(csv_file, fieldnames=list(rows[0]) if rows else [])
        writer.writeheader()
        writer.writerows(rows)
    print(f"JSON results: {output}")
    print(f"CSV summary:  {csv_path}")


if __name__ == "__main__":
    main()
