"""Sweep request concurrency and prompt length, reporting latency, throughput and KV use.

Example (run inside the WSL environment with the model installed):

    python benchmarks/context_concurrency.py \\
        --model ~/huggingface/Qwen3-0.6B \\
        --context-lengths 512,1024,2048,4096 \\
        --concurrency 1,2,4,8,16 --repeats 3 --max-output-tokens 32

The workload uses deterministic synthetic token IDs. Each matrix point submits a
simultaneous burst to the online GenerationManager and keeps per-request samples
in JSON; a compact CSV is written beside it. KV capacity is taken from the
allocated cache tensors and scheduler block pools, not inferred from model size.
"""
